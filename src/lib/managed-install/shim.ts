/**
 * PATH shims for the managed install.
 *
 * The launcher (`<APP_DIR>/m/<kind>/launcher.mjs`) is the stable thing; a shim is
 * just the name a shell can type. Two rules make these safe to write:
 *
 * 1. **Marker-required.** A file is only overwritten if it carries
 *    `MANAGED_MARKER`. Anything else is left alone with a warning, because the
 *    alternative is deleting a user's own `github-router` script — the
 *    `lstat`-then-refuse discipline already used for `.github-router-managed`
 *    (`src/lib/paths.ts:786-812`).
 * 2. **Never in `PATHS.TOOLBELT_BIN_DIR`.** `pruneUnexpected`
 *    (`src/lib/toolbelt/provision.ts:96-110`) deletes anything not in its
 *    manifest, so a shim placed there is deleted on the next launch — a bug that
 *    only shows up on the second run.
 *
 * The directory is `<APP_DIR>/cli-bin` (`paths.ts` → `cliBinDir`), NOT
 * `~/.local/bin`: the app dir is the one location the router already owns and
 * GC already understands, and writing into `~/.local/bin` would mean guessing
 * whether that directory belongs to us. The consequence is that the directory is
 * usually NOT on PATH, so `update` prints one copy-pasteable line (`pathHint`)
 * instead of editing a shell rc file we cannot verify.
 *
 * The shims intentionally do NOT hardcode a runtime. They exec the launcher with
 * whatever `node`/`bun` the shell resolves, so a future nvm switch keeps working
 * and there is no baked interpreter path to go stale.
 */

import { realpathSync } from "node:fs"
import fs from "node:fs/promises"
import path from "node:path"

import consola from "consola"

import { writeFileAtomic } from "../atomic-file"
import { MANAGED_MARKER, hasManagedMarker } from "./launcher"
import { type ManagedKind, cliBinDir, launcherPath, shimPath } from "./paths"

/** The command names we own. `github-router` for self, `pi` only when managed. */
export function shimBases(kind: ManagedKind): Array<string> {
  return kind === "self" ? ["github-router"] : ["pi"]
}

export type ShimWriteOutcome = "written" | "updated" | "unchanged" | "refused"

export interface ShimResult {
  path: string
  outcome: ShimWriteOutcome
}

/**
 * POSIX shim body.
 *
 * `exec` (not a subshell) so the payload inherits the caller's stdio, exit
 * status, and signal disposition — a hook that runs
 * `github-router internal-…` must see the child's exit code directly.
 *
 * The runtime is chosen by trying the launcher's own candidates rather than
 * hardcoding: `command -v node` then `command -v bun`. If neither exists the
 * message names the missing dependency instead of failing with "not found".
 */
function posixShim(launcher: string): string {
  return `#!/bin/sh
# ${MANAGED_MARKER} — generated by \`github-router update\`. Do not edit.
# Re-run \`github-router update\` to refresh; deleting this file is safe.
set -e
LAUNCHER="${launcher}"
if [ ! -f "$LAUNCHER" ]; then
  echo "github-router: the managed launcher is missing ($LAUNCHER)." >&2
  echo "  Reinstall: npm install -g github-router" >&2
  exit 78
fi
for RUNTIME in node bun; do
  if command -v "$RUNTIME" >/dev/null 2>&1; then
    exec "$RUNTIME" "$LAUNCHER" "$@"
  fi
done
echo "github-router: neither node nor bun is on PATH." >&2
echo "  Install Node.js 20+ (https://nodejs.org) and try again." >&2
exit 127
`
}

/**
 * Windows `.cmd` shim.
 *
 * `%~dp0` is deliberately NOT used: the shim lives in `<APP_DIR>\\cli-bin` while
 * the launcher lives in `<APP_DIR>\\m\\<kind>`, so the absolute path is baked in
 * (and rewritten by `github-router update` if the app dir ever moves).
 *
 * `where` (not `which`) is the Windows lookup, and `>nul 2>nul` keeps a missing
 * candidate from printing. `%*` forwards the original argv verbatim, which is
 * what `buildExecInvocation`'s quoting expects downstream.
 */
function cmdShim(launcher: string): string {
  return `@echo off\r
rem ${MANAGED_MARKER} - generated by github-router update. Do not edit.\r
setlocal\r
set "LAUNCHER=${launcher}"\r
if not exist "%LAUNCHER%" (\r
  echo github-router: the managed launcher is missing ^("%LAUNCHER%^). 1>&2\r
  echo   Reinstall: npm install -g github-router 1>&2\r
  exit /b 78\r
)\r
rem %ERRORLEVEL% inside a ( ) block is expanded when the BLOCK is parsed, so a\r
rem 'where node && ( node .. & exit /b %ERRORLEVEL% )' would report where's status\r
rem instead of the launcher's, so every Windows hook would look successful. The\r
rem goto-based flow instead of blocks: each %ERRORLEVEL% below is on its own line,\r
rem expanded at execution, after the child has exited. Delayed expansion is not an\r
rem option here — it would mangle '!' in forwarded arguments.\r
where node >nul 2>nul\r
if not errorlevel 1 goto :gh_shim_node\r
where bun >nul 2>nul\r
if not errorlevel 1 goto :gh_shim_bun\r
echo github-router: neither node nor bun is on PATH. 1>&2\r
echo   Install Node.js 20+ ^(https://nodejs.org^) and try again. 1>&2\r
exit /b 127\r
:gh_shim_node\r
node "%LAUNCHER%" %*\r
exit /b %ERRORLEVEL%\r
:gh_shim_bun\r
bun "%LAUNCHER%" %*\r
exit /b %ERRORLEVEL%\r
`
}

/**
 * PowerShell shim.
 *
 * Present because a `.cmd` is invisible to a bare `github-router` in PowerShell
 * only in theory (PATHEXT covers it) but fails in practice under constrained
 * execution policies that block `.cmd`. `$LASTEXITCODE` is propagated explicitly
 * — PowerShell would otherwise return 0 for a failed native command, turning a
 * hook failure into a success.
 */
function ps1Shim(launcher: string): string {
  return `# ${MANAGED_MARKER} - generated by github-router update. Do not edit.
$ErrorActionPreference = "Stop"
$Launcher = '${launcher.replace(/'/g, "''")}'
if (-not (Test-Path -LiteralPath $Launcher)) {
  [Console]::Error.WriteLine("github-router: the managed launcher is missing ($Launcher).")
  [Console]::Error.WriteLine("  Reinstall: npm install -g github-router")
  exit 78
}
foreach ($Runtime in @("node", "bun")) {
  $cmd = Get-Command $Runtime -ErrorAction SilentlyContinue
  if ($cmd) {
    & $cmd.Source $Launcher @args
    exit $LASTEXITCODE
  }
}
[Console]::Error.WriteLine("github-router: neither node nor bun is on PATH.")
[Console]::Error.WriteLine("  Install Node.js 20+ (https://nodejs.org) and try again.")
exit 127
`
}

export interface ShimBody {
  path: string
  content: string
  /** POSIX shims need the executable bit; `.cmd`/`.ps1` must not have it set oddly. */
  mode: number
}

/** The exact files `ensureShims` should own for `kind` on this platform. */
export function shimBodies(
  kind: ManagedKind,
  launcher = launcherPath(kind),
  platform: NodeJS.Platform = process.platform,
): Array<ShimBody> {
  const out: Array<ShimBody> = []
  for (const base of shimBases(kind)) {
    if (platform === "win32") {
      out.push({ path: shimPath(base, platform), content: cmdShim(launcher), mode: 0o644 })
      out.push({
        path: shimPath(base, platform).replace(/\.cmd$/, ".ps1"),
        content: ps1Shim(launcher),
        mode: 0o644,
      })
    } else {
      out.push({ path: shimPath(base, platform), content: posixShim(launcher), mode: 0o755 })
    }
  }
  return out
}

/**
 * Write (or refresh) the shims.
 *
 * Refusal is per-file and non-fatal: one file we do not own must not stop the
 * other from being written, and it must not fail an update — the payload is
 * already live by the time this runs.
 */
export async function ensureShims(
  kind: ManagedKind,
  launcher = launcherPath(kind),
  platform: NodeJS.Platform = process.platform,
): Promise<Array<ShimResult>> {
  const results: Array<ShimResult> = []
  for (const body of shimBodies(kind, launcher, platform)) {
    results.push(await writeShim(body))
  }
  return results
}

async function writeShim(body: ShimBody): Promise<ShimResult> {
  const existing = await readIfExists(body.path)
  if (existing !== null && !hasManagedMarker(existing)) {
    consola.warn(
      `Refusing to overwrite ${body.path}: it exists and was not written by github-router. Move it aside if you want the managed shim there.`,
    )
    return { path: body.path, outcome: "refused" }
  }
  if (existing === body.content) {
    // Content equality is not "nothing to do": a shim that lost its executable
    // bit (unzip, a copy, a restore from a backup, an inconsistent umask) is
    // `permission denied` forever while this branch keeps saying "unchanged".
    // Cheap to check, and the only repair opportunity we get.
    const mode = await fs.stat(body.path).then(
      (st) => st.mode & 0o777,
      () => null,
    )
    if (mode === null || (mode & body.mode) !== body.mode) {
      await fs.chmod(body.path, body.mode).catch(() => {})
      return { path: body.path, outcome: "updated" }
    }
    return { path: body.path, outcome: "unchanged" }
  }

  await fs.mkdir(path.dirname(body.path), { recursive: true, mode: 0o755 })
  try {
    await writeFileAtomic(body.path, body.content, { mode: body.mode })
  } catch (err) {
    // A read-only cli-bin (or a managed container home) is not a reason to
    // fail an update; the launcher is already live and can be invoked directly.
    consola.warn(`Could not write shim ${body.path}:`, err)
    return { path: body.path, outcome: "refused" }
  }
  // `writeFileAtomic` sets the mode on the temp file, but a rename can drop it on
  // some Windows/network filesystems; set it again best-effort.
  await fs.chmod(body.path, body.mode).catch(() => {})
  return { path: body.path, outcome: existing === null ? "written" : "updated" }
}

async function readIfExists(file: string): Promise<string | null> {
  try {
    // lstat first: a symlink at the shim path must be refused, not followed.
    const stat = await fs.lstat(file)
    if (!stat.isFile()) return ""
    return await fs.readFile(file, "utf8")
  } catch {
    return null
  }
}

/** Absolute path of the directory the shims live in. */
export function shimDir(): string {
  return cliBinDir()
}

/**
 * Whether `dir` is already on `PATH`.
 *
 * Compares resolved forms: `/var/…` vs `/private/var/…` on macOS and a
 * case-insensitive Windows path would both otherwise report "not on PATH" for a
 * directory that is.
 */
export function isOnPath(
  dir: string,
  env: NodeJS.ProcessEnv = process.env,
  platform: NodeJS.Platform = process.platform,
): boolean {
  const raw = env.PATH ?? env.Path ?? env.path ?? ""
  const sep = platform === "win32" ? ";" : ":"
  const target = canonicalPath(dir, platform)
  return raw.split(sep).some((entry) => entry.length > 0 && canonicalPath(entry, platform) === target)
}

function canonicalPath(value: string, platform: NodeJS.Platform): string {
  const trimmed = value.replace(/[/\\]+$/, "")
  if (platform === "win32") return trimmed.toLowerCase()
  // Resolve symlinks so `/var/...` and `/private/var/...` compare equal — macOS
  // reports one and accepts the other, so a PATH entry that IS this directory
  // would otherwise read as "not on PATH" and print a pointless PATH edit.
  // Only existing paths are resolved (`realpathSync` throws for the rest, and a
  // PATH entry that does not exist cannot be this directory anyway).
  try {
    return realpathSync(trimmed)
  } catch {
    return trimmed
  }
}

/**
 * One actionable line when the shim directory is not on PATH, else `null`.
 *
 * Returned rather than logged for the same reason as
 * `hookLauncherDegradedWarning`: `claude`/`codex` redirect `consola` to the error
 * log, so a warning logged deep inside update is invisible exactly where it
 * matters. The CLI prints it next to the readiness line.
 */
export function pathHint(
  dir = shimDir(),
  env: NodeJS.ProcessEnv = process.env,
  platform: NodeJS.Platform = process.platform,
): string | null {
  if (isOnPath(dir, env, platform)) return null
  if (platform === "win32") {
    // NOT `setx PATH "%PATH%;<dir>"`. That is the suggestion everyone writes and
    // it is actively destructive: `%PATH%` at that moment is the MACHINE path
    // followed by the USER path, so pasting it folds the machine entries into the
    // user path permanently, and `setx` truncates at 1024 characters — which
    // silently drops the tail of a developer's PATH. Print the value and let the
    // user add it through the UI, which edits only the user scope.
    return (
      `Add ${dir} to PATH to run \`github-router\` from any shell.\n`
      + `  Windows: Settings > System > About > Advanced system settings > Environment Variables,\n`
      + `  edit "User variables" PATH and add: ${dir}`
    )
  }
  return `Add ${dir} to PATH to run \`github-router\` from any shell:\n  export PATH="${dir}:$PATH"`
}

/**
 * Whether `candidate` is our own shim (vs a user's real install).
 *
 * Pi precedence needs this: a `pi` on PATH that is *our* shim must not be
 * treated as the user's own Pi, or the managed install would shadow itself.
 * Detected by the marker line, never by basename — a user's `~/bin/pi` is
 * theirs.
 */
export async function isOurShim(candidate: string): Promise<boolean> {
  const content = await readIfExists(candidate)
  return content !== null && hasManagedMarker(content)
}

