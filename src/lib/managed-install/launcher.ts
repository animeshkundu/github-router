/**
 * The stable launcher: `<APP_DIR>/m/<kind>/launcher.mjs`.
 *
 * This file is the entire point of the managed layout. Shims (and anything else
 * that wants a version-independent path) exec THIS, and it figures out which
 * concrete payload is live by reading `current.json` and re-execing it. It is
 * written once and never swapped, so a shim baked onto PATH years ago keeps
 * working across every future version — which is exactly the property
 * `claude`'s native installer has and `npx` does not.
 *
 * It is generated as SOURCE TEXT rather than built as a bundle entry, and that
 * is deliberate:
 *
 * - it must survive when the package tree it came from is deleted (that is the
 *   `bunx`/`npx` case this feature exists for), so it cannot carry a single
 *   non-`node:` import;
 * - it is ~150 lines of self-contained logic, so a build entry would add a
 *   fourth bundle, a sidecar digest, and a publish step for no benefit;
 * - `tests/isolated/managed-launcher.test.ts` runs the real emitted file under
 *   the real `node`, on every platform CI has, which pins behaviour harder than
 *   a typecheck would.
 *
 * What it must never do: resolve the version itself, install anything, or touch
 * the network. Every failure has to be a message plus a non-zero exit, because
 * the caller is a shell or a hook with no way to recover.
 */

import fs from "node:fs/promises"

import consola from "consola"

import { writeFileAtomic } from "../atomic-file"
import { type ManagedKind, launcherPath, managedRoot } from "./paths"

/**
 * Marker line every generated file carries.
 *
 * `shim.ts` uses the same idea for its guards: a file is only ever overwritten
 * if it contains this marker, so a user's own script that happens to sit at the
 * same path is never clobbered. Keep the two constants in sync — `LAUNCHER_BODY`
 * includes it as a comment, and `hasManagedMarker()` is the reader.
 */
export const MANAGED_MARKER = "github-router-managed-file"

export function hasManagedMarker(content: string): boolean {
  return content.includes(MANAGED_MARKER)
}

/**
 * The launcher program.
 *
 * Constraints on the body (all enforced by tests):
 *   - no top-level import other than `node:` builtins;
 *   - no reference to `github-router` package code;
 *   - must run on Node 20 and on bun.
 */
const LAUNCHER_BODY = String.raw`
// ${MANAGED_MARKER} — generated by \`github-router update\`. Do not edit.
// Resolves <dir>/current.json and re-execs the payload it names.
import { spawn } from "node:child_process"
import { readFileSync, existsSync, statSync, writeSync } from "node:fs"
import { dirname, join, isAbsolute } from "node:path"
import { fileURLToPath } from "node:url"

const here = dirname(fileURLToPath(import.meta.url))
// Test seams, gated behind an explicit opt-in. Ungated they are a footgun with a
// security edge: a stale GH_ROUTER_MANAGED_ENTRY in a user's environment would
// execute an ARBITRARY file on every launch (it bypasses the traversal/absolute
// checks below, which is the whole point of an override), and a stale
// GH_ROUTER_MANAGED_DRY_RUN would make every hook exit 0 having printed JSON
// instead of doing its work — a success that means nothing.
const TEST_SEAMS = process.env.GH_ROUTER_MANAGED_TEST === "1"
const ENTRY_OVERRIDE = TEST_SEAMS ? process.env.GH_ROUTER_MANAGED_ENTRY : undefined
const DRY_RUN = TEST_SEAMS && process.env.GH_ROUTER_MANAGED_DRY_RUN === "1"

function fail(message, code) {
  // writeSync, not process.stderr.write: on a PIPE stderr is asynchronous, and
  // process.exit tears the loop down before the bytes reach the reader — so a
  // hook or a CI step saw a bare exit 78 with no explanation, which is precisely
  // the case this message exists for.
  try {
    writeSync(2, "github-router: " + message + "\n")
  } catch {
    // Best effort: still exit with the code.
  }
  process.exit(typeof code === "number" ? code : 1)
}

function readPointer() {
  const file = join(here, "current.json")
  let raw
  try {
    raw = readFileSync(file, "utf8")
  } catch (err) {
    if (err && err.code === "ENOENT") {
      fail(
        "no managed install is active (" + file + " is missing).\n" +
          "  Run: github-router update\n" +
          "  Or reinstall: npm install -g github-router",
        78
      )
    }
    fail("could not read " + file + ": " + (err && err.message ? err.message : String(err)))
  }
  let parsed
  try {
    parsed = JSON.parse(raw)
  } catch {
    fail(file + " is not valid JSON. Run: github-router update")
  }
  if (!parsed || typeof parsed !== "object") fail(file + " is not a pointer object. Run: github-router update")
  if (parsed.schemaVersion !== 1) {
    fail(
      "unsupported pointer schema " + String(parsed.schemaVersion) + ". This launcher is too old for the installed layout; reinstall github-router.",
      78
    )
  }
  if (typeof parsed.version !== "string" || typeof parsed.entry !== "string") {
    fail(file + " is missing its version/entry fields. Run: github-router update")
  }
  // A version string becomes a path segment: never let it climb out.
  if (parsed.version.indexOf("/") >= 0 || parsed.version.indexOf("\\") >= 0 || parsed.version.indexOf("..") >= 0) {
    fail(file + " names an invalid version. Run: github-router update")
  }
  // The entry becomes an argv the runtime executes. Absolute paths and
  // traversal are refused for the same reason the writer refuses them.
  if (isAbsolute(parsed.entry) || parsed.entry.split(/[\\/]/).indexOf("..") >= 0) {
    fail(file + " names an unsafe entry. Run: github-router update")
  }
  return parsed
}

/**
 * Pick the runtime for the payload.
 *
 * Order: whatever is already running this launcher, then the pointer's
 * \`runtimeHint\`, then \`node\` on PATH.
 *
 * \`process.execPath\` comes first because it is the only candidate whose version
 * we can check for free: spawning \`node --version\` on every launch is a real
 * cost, and this file runs on every CLI invocation a session makes. That check
 * matters when a \`bunx\` user's bun reports a node-compat major below the
 * payload's floor — rare, but it is the difference between a clear engine error
 * and a mystery crash.
 *
 * \`runtimeHint\` is only a FALLBACK, never authoritative: nvm/fnm/volta/brew
 * delete the previous interpreter on every upgrade, so trusting a recorded
 * absolute path is exactly how a launcher "stops working after a node upgrade".
 */
function isFile(candidate) {
  try {
    return typeof candidate === "string" && candidate.length > 0 && statSync(candidate).isFile()
  } catch {
    return false
  }
}

function runningNodeMajor() {
  const running = process.versions && process.versions.node
  if (!running) return null
  const major = Number(String(running).split(".")[0])
  return Number.isNaN(major) ? null : major
}

/** \`engines.node\` major from the PAYLOAD's package.json, or null. */
function enginesNodeMajor(entryPath) {
  let dir = dirname(entryPath)
  for (let i = 0; i < 6; i++) {
    const candidate = join(dir, "package.json")
    if (existsSync(candidate)) {
      try {
        const pkg = JSON.parse(readFileSync(candidate, "utf8"))
        if (pkg && typeof pkg.name === "string") {
          const range = pkg.engines && pkg.engines.node
          if (typeof range !== "string") return null
          const match = range.match(/(\d+)/)
          return match ? Number(match[1]) : null
        }
      } catch {
        // Keep walking.
      }
    }
    const parent = dirname(dir)
    if (parent === dir) break
    dir = parent
  }
  return null
}

function chooseRuntime(pointer, entryPath) {
  const minMajor = enginesNodeMajor(entryPath)
  const mine = runningNodeMajor()
  // Unknown floor or unknown running version: do not filter, keep the runtime
  // the user chose. A wrong guess here is worse than an engine mismatch.
  const mineOk = minMajor === null || mine === null || mine >= minMajor
  if (mineOk && isFile(process.execPath)) return process.execPath

  if (isFile(pointer.runtimeHint)) return pointer.runtimeHint

  const pathEnv = process.env.PATH || ""
  const sep = process.platform === "win32" ? ";" : ":"
  const names = process.platform === "win32" ? ["node.exe", "node"] : ["node"]
  for (const dir of pathEnv.split(sep)) {
    if (!dir) continue
    for (const name of names) {
      const candidate = join(dir, name)
      if (isFile(candidate)) return candidate
    }
  }
  // Nothing better: let the spawn fail with its own message.
  return process.execPath
}

const pointer = readPointer()
const versionDir = join(here, pointer.version)
const entryPath = ENTRY_OVERRIDE || join(versionDir, pointer.entry)

if (!existsSync(entryPath)) {
  fail(
    "the live payload is missing: " + entryPath + "\n" +
      "  The install is incomplete. Run: github-router update",
    78
  )
}

if (DRY_RUN) {
  // Test/diagnostic hook: report what WOULD run, without running it. Used by
  // the managed-install e2e test to prove a launch landed on the managed tree
  // without parsing debug logs.
  process.stdout.write(JSON.stringify({ version: pointer.version, entryPath }) + "\n")
  process.exit(0)
}

const runtime = chooseRuntime(pointer, entryPath)

const SIGNALS = ["SIGINT", "SIGTERM", "SIGHUP"]
const SIGNAL_NUMBERS = { SIGHUP: 1, SIGINT: 2, SIGTERM: 15 }
// Registered BEFORE the spawn: a signal that arrives between \`spawn\` returning
// and the handler being installed kills this launcher with the default
// disposition and leaves the payload running with nobody forwarding to it.
let child = null
for (const signal of SIGNALS) {
  try {
    process.on(signal, () => {
      try {
        if (child) child.kill(signal)
      } catch {
        // already gone
      }
    })
  } catch {
    // Platform without this signal.
  }
}

try {
  child = spawn(runtime, [entryPath, ...process.argv.slice(2)], {
    stdio: "inherit",
    windowsHide: true,
    env: process.env,
  })
} catch (err) {
  fail("could not start " + runtime + ": " + (err && err.message ? err.message : String(err)))
}

child.on("error", (err) => {
  fail("could not start " + runtime + ": " + (err && err.message ? err.message : String(err)))
})

child.on("exit", (code, signal) => {
  if (signal) {
    // Mirror the child's fate so a supervisor (systemd, a CI runner, a hook
    // wrapper) sees a signal death rather than a generic exit 1.
    //
    // The forwarding handlers above MUST go first: Node does not re-raise a
    // signal that has a listener, so leaving them installed makes the re-raise a
    // no-op that falls through to exit 0 — an interrupted launch reports success.
    // 128+n is also set, for a signal that cannot be re-raised at all.
    for (const name of SIGNALS) process.removeAllListeners(name)
    process.exitCode = 128 + (SIGNAL_NUMBERS[signal] || 0)
    try {
      process.kill(process.pid, signal)
    } catch {
      process.exit(process.exitCode)
    }
    return
  }
  process.exit(typeof code === "number" ? code : 1)
})
`.trimStart()

/** The exact bytes written to `launcher.mjs` for `kind`. */
export function launcherSource(): string {
  return LAUNCHER_BODY.endsWith("\n") ? LAUNCHER_BODY : `${LAUNCHER_BODY}\n`
}

export interface EnsureLauncherResult {
  path: string
  written: boolean
}

/**
 * Write the launcher if it is absent or stale.
 *
 * Content-checked, not existence-checked: a future release can improve the
 * launcher (a new signal, a new runtime rule) and have it take effect on the
 * next run of any version, without a migration step. It is safe to rewrite
 * because nothing holds this file open — the shims exec it and the process
 * exits when the payload does — and `writeFileAtomic` means a concurrent launch
 * sees either the old bytes or the new bytes, never a truncation.
 */
export async function ensureLauncher(kind: ManagedKind): Promise<EnsureLauncherResult> {
  const file = launcherPath(kind)
  const desired = launcherSource()
  try {
    const current = await fs.readFile(file, "utf8")
    if (current === desired) return { path: file, written: false }
  } catch {
    // Absent or unreadable: write it below.
  }
  await fs.mkdir(managedRoot(kind), { recursive: true })
  try {
    await writeFileAtomic(file, desired, { mode: 0o755 })
  } catch (err) {
    // A virus scanner or an EDR holding `launcher.mjs` turns the rename into
    // EPERM. The PAYLOAD is already live and the pointer names it, so failing the
    // whole update here would report a broken install for a cosmetic miss; the
    // next `update` retries. Same policy as `writeShim`.
    consola.warn(`Could not write the managed launcher ${file}:`, err)
    return { path: file, written: false }
  }
  return { path: file, written: true }
}
